"""Agent module for the Experiment Analyst Agent.

This module defines a lightweight LLM-based agent that uses Ollama as the
local model provider. The agent receives a factual business context and a user
question, then returns a structured analytical response.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import ollama

from experiment_analyst_agent.prompts import SYSTEM_PROMPT
from experiment_analyst_agent.data_loader import load_activations_data
from experiment_analyst_agent.metrics import (
    compute_activation_rate,
    compute_activation_rate_by_experiment,
    compute_segment_analysis
)


@dataclass
class AgentResponse:
    """Structured response returned by the agent.

    Attributes:
        content: Text generated by the language model.
        model: Name of the model used to generate the response.
    """

    content: str
    model: str


class ExperimentAnalystAgent:
    """A simple business experimentation analyst agent.

    The agent is designed to support A/B testing analysis in a business context.
    It uses a system prompt to define the agent's role, rules, and expected
    behavior.

    Parameters:
        model_name: Name of the Ollama model to use.
    """

    def __init__(self, model_name: str = "qwen2.5:3b") -> None:
        self.model_name = model_name

    def analyze(self, business_context: str, user_question: str, path_data: str) -> AgentResponse:
        """Generate an analytical response based on context and user question.

        Args:
            business_context: Factual information available to the agent.
            user_question: Business or analytical question asked by the user.
            path_data: Path for data

        Returns:
            AgentResponse containing the generated answer and model name.
        """

        messages: list[dict[str, str]] = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": self._build_user_prompt(
                    business_context=business_context,
                    user_question=user_question,
                    path_data=path_data,

                ),
            },
        ]

        response: dict[str, Any] = ollama.chat(
            model=self.model_name,
            messages=messages,
        )

        return AgentResponse(
            content=response["message"]["content"],
            model=self.model_name,
        )

    @staticmethod
    def _build_user_prompt(business_context: str, user_question: str, path_data: str) -> str:
        """Build the final user prompt sent to the model.

        Args:
            business_context: Factual context computed from the dataset.
            user_question: User's analytical question.

        Returns:
            A structured prompt combining context and question.
        """

        data = load_activations_data(path_data)

        total_activation_rate = compute_activation_rate(data)

        activation_rate_by_exp = compute_activation_rate_by_experiment(data)

        activation_rate_by_groups = compute_segment_analysis(data)

        return f"""

Total rate: 

{total_activation_rate}

Rate by experiment: 

{activation_rate_by_exp}

Rate by groups: 

{activation_rate_by_groups}

Business context:

{business_context}

User question:

{user_question}

Instructions:
- Use only the information provided in the business context.
- If the evidence is insufficient, say so explicitly.
- Separate facts, hypotheses, and recommended next analyses.
- Keep the answer useful for a business audience.
""".strip()